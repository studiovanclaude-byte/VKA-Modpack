#!/usr/bin/env python3
"""VKA v5: clean 16:9 illustration WITHOUT baked-in buttons.

Controls are generated by Java GuiGraphicsExtractor at runtime, including
labels, icons, raised stone faces, and pressed 3D depth. This script generates
ONLY the backdrop; it never cuts/pastes any button image.
"""
from pathlib import Path
import base64, hashlib, io, argparse
from PIL import Image, ImageDraw, ImageFilter

BASE = (1672, 941)
ART = Path(__file__).resolve().parents[1] / "art/vka-clean-native-v4.webp.b64"
EXPECTED_SHA = "d3a0a3b8e8080e2d69fea2cad6011d9afca0d6e65143416fdb10e7fcc0beec8b"
parser=argparse.ArgumentParser()
parser.add_argument("--output",required=True)
args=parser.parse_args()
payload=base64.b64decode("".join(ART.read_text(encoding="ascii").split()),validate=True)
if hashlib.sha256(payload).hexdigest()!=EXPECTED_SHA:
    raise SystemExit("La référence VKA n'a pas la bonne empreinte")
with Image.open(io.BytesIO(payload)) as input_image:
    source=input_image.convert("RGB")
assert source.size==BASE, source.size
scene=source.copy()

# Reconstruire uniquement le matériau sombre du panneau central, sans
# récupérer les boutons, libellés ni icônes de la maquette d'origine.
left,top,right,bottom=409,455,1249,819
patch=Image.new("RGB",(right-left,bottom-top))
pix=patch.load()
original=source.load()
for y in range(top,bottom):
    left_color=original[390,y]
    right_color=original[1265,y]
    for x in range(left,right):
        t=(x-left)/float(right-left-1)
        pix[x-left,y-top]=tuple(round(left_color[c]*(1-t)+right_color[c]*t) for c in range(3))
mask=Image.new("L",patch.size,0)
draw=ImageDraw.Draw(mask)
draw.rectangle((9,9,patch.width-10,patch.height-10),fill=255)
mask=mask.filter(ImageFilter.GaussianBlur(radius=8))
scene.paste(patch,(left,top),mask)
scene=scene.resize((BASE[0]*2,BASE[1]*2),Image.Resampling.LANCZOS)
# Léger accent de netteté uniquement, sans halos ni franges autour des lettres.
scene=scene.filter(ImageFilter.UnsharpMask(radius=0.65,percent=65,threshold=4))

output=Path(args.output)
output.mkdir(parents=True,exist_ok=True)
destination=output/"vka_menu_hd.png"
scene.save(destination,optimize=True)
assert scene.size==(3344,1882)
print("VKA v5: scene without UI widgets:",destination,scene.size,destination.stat().st_size)

# Matière de pierre dédiée aux vraies faces 3D, créée indépendamment du
# décor. Elle ne contient ni vieux bouton, ni cadre, ni libellé.
import random
rng=random.Random(1250)
tile_w,tile_h=1024,192
coarse=Image.new("L",(64,12))
coarse.putdata([rng.randrange(55,190) for _ in range(64*12)])
coarse=coarse.resize((tile_w,tile_h),Image.Resampling.BICUBIC).filter(ImageFilter.GaussianBlur(4.0))
fine=Image.new("L",(tile_w,tile_h))
fine.putdata([rng.randrange(60,195) for _ in range(tile_w*tile_h)])
cdata=list(coarse.getdata())
fdata=list(fine.getdata())
stone=Image.new("RGB",(tile_w,tile_h))
out=[]
for index,(lo,hi) in enumerate(zip(cdata,fdata)):
    y=index//tile_w
    brightness=int((lo-128)*0.27+(hi-128)*0.20)
    vignette=int(7*abs(y-tile_h/2)/(tile_h/2))
    out.append(tuple(max(0,min(255,v+brightness-vignette)) for v in (61,71,65)))
stone.putdata(out)
draw=ImageDraw.Draw(stone,"RGB")
for i in range(25):
    x=rng.randrange(tile_w)
    y=rng.randrange(10,tile_h-10)
    span=rng.randrange(8,75)
    draw.line((x,y,x+span,y+rng.randrange(-8,9)),fill=(45,53,47),width=1)
for i in range(30):
    x,y=rng.randrange(tile_w),rng.randrange(tile_h)
    draw.point((x,y),fill=(129,140,124))
stone.save(output/"vka_stone_face.png",optimize=True)
print("VKA v5: procedural stone material:",stone.size)

